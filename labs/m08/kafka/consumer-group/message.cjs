// ЗАДАНИЕ: преврати событие в сообщение Kafka так, чтобы все события одного пользователя попадали в ОДНУ партицию
// (и, значит, читались по порядку). Подсказка: порядок гарантируется только внутри партиции, а партицию выбирает ключ.
// Сейчас ключа нет: сообщения расходятся по партициям, и порядок для пользователя теряется.
function toKafkaMessage(event) {
  return { value: JSON.stringify(event) };
}

module.exports = { toKafkaMessage };
